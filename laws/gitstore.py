"""Render acts into the law-content git repository.

This is a *separate* repository from the LawHub code. Layout::

    pl/DU/1997/602/
        meta.json      act metadata
        text.md        human-readable text, one provision per line
        units.jsonl    machine-readable provisions, one JSON object per line

One provision per line keeps `git diff` (and pull-request diffs) aligned with
legal units. Each import of a new version is one commit whose author date is
the version's legal date, so `git log` reads as the act's legal history.
Changes that are *proposed* go on a branch and become a pull request; merging
it is how a change lands in the corpus.
"""

from __future__ import annotations

import json
import os
import subprocess
from dataclasses import dataclass
from pathlib import Path

from laws.domain.units import ActText, Unit

BOT_NAME = "LawHub Bot"
BOT_EMAIL = "bot@lawhub.invalid"


@dataclass
class CommitResult:
    sha: str
    changed: bool


class GitStore:
    def __init__(self, root: Path | str):
        self.root = Path(root)

    def init(self) -> None:
        self.root.mkdir(parents=True, exist_ok=True)
        if not (self.root / ".git").exists():
            self._git("init", "-q", "-b", "main")
            (self.root / "README.md").write_text(
                "# LawHub law corpus\n\nGenerated by LawHub. One directory per act: "
                "`<jurisdiction>/<source id>/`.\n",
                encoding="utf-8",
            )
            self._git("add", "README.md")
            self._commit("Initialize law corpus", date=None)

    @staticmethod
    def act_path(text: ActText) -> str:
        return f"{text.act.jurisdiction}/{text.act.source_id.strip('/')}"

    def write_version(self, text: ActText, *, branch: str | None = None) -> CommitResult:
        """Write one act version and commit it (on `branch` if given)."""
        self.init()
        if branch:
            self._git("checkout", "-q", "-B", branch)
        rel = self.act_path(text)
        target = self.root / rel
        target.mkdir(parents=True, exist_ok=True)
        (target / "meta.json").write_text(_meta_json(text), encoding="utf-8")
        (target / "text.md").write_text(render_markdown(text), encoding="utf-8")
        (target / "units.jsonl").write_text(render_units(text.root), encoding="utf-8")
        self._git("add", rel)
        if not self._git("status", "--porcelain", rel).strip():
            return CommitResult(self.head(), changed=False)
        self._commit(f"{rel}: {text.version_label}\n\n{text.act.title}", date=text.version_date)
        return CommitResult(self.head(), changed=True)

    def head(self) -> str:
        return self._git("rev-parse", "HEAD").strip()

    def _commit(self, message: str, date: str | None) -> None:
        env = {}
        if date:
            stamp = f"{date}T12:00:00+00:00"
            env = {"GIT_AUTHOR_DATE": stamp, "GIT_COMMITTER_DATE": stamp}
        self._git("commit", "-q", "-m", message, env=env)

    def _git(self, *args: str, env: dict | None = None) -> str:
        full_env = {
            **os.environ,
            "GIT_AUTHOR_NAME": BOT_NAME,
            "GIT_AUTHOR_EMAIL": BOT_EMAIL,
            "GIT_COMMITTER_NAME": BOT_NAME,
            "GIT_COMMITTER_EMAIL": BOT_EMAIL,
            **(env or {}),
        }
        return subprocess.run(
            ["git", "-C", str(self.root), *args],
            check=True,
            capture_output=True,
            text=True,
            env=full_env,
        ).stdout


def _meta_json(text: ActText) -> str:
    act = text.act
    meta = {
        "jurisdiction": act.jurisdiction,
        "source_id": act.source_id,
        "title": act.title,
        "native_type": act.native_type,
        "act_type": act.act_type,
        "status": act.status,
        "in_force": act.in_force,
        "published_on": act.published_on,
        "display_address": act.display_address,
        "source_url": act.source_url,
        "version": {"id": text.version_id, "date": text.version_date, "label": text.version_label},
    }
    return json.dumps(meta, ensure_ascii=False, indent=2) + "\n"


_HEADING_LEVEL = {"part": 2, "book": 2, "title": 2, "division": 3, "chapter": 4, "section": 5}


def render_markdown(text: ActText) -> str:
    lines = [f"# {text.act.title}", "", f"*{text.version_label}*", ""]

    def visit(unit: Unit, list_depth: int) -> None:
        if unit.kind in _HEADING_LEVEL:
            heading = f"{unit.label} {unit.heading or ''}".strip()
            lines.extend(["", f"{'#' * _HEADING_LEVEL[unit.kind]} {heading}", ""])
            child_depth = 0
        elif unit.kind == "article":
            lines.extend(["", f"**{unit.label}** {unit.text}".rstrip()])
            child_depth = 1
        else:
            lines.append(f"{'  ' * (list_depth - 1)}{unit.label} {unit.text}".rstrip())
            child_depth = list_depth + 1
        for child in unit.children:
            visit(child, child_depth)
        if unit.tail:
            lines.append(unit.tail)

    for child in text.root.children:
        visit(child, 1)
    return "\n".join(lines).strip() + "\n"


def render_units(root: Unit) -> str:
    rows = []
    for unit, depth in root.walk():
        if unit.kind == "act":
            continue
        rows.append(
            json.dumps(
                {
                    "address": unit.address,
                    "kind": unit.kind,
                    "label": unit.label,
                    "heading": unit.heading,
                    "text": unit.text,
                    "tail": unit.tail,
                    "depth": depth,
                },
                ensure_ascii=False,
            )
        )
    return "\n".join(rows) + "\n"
